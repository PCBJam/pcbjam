#!/usr/bin/env node

import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import {
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REQUIRED_DAFNY = "4.11.0+fcb2042d6d043a2634f0854338c08feeaaaf4ae2";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const source = join(root, "formal/yjs/YjsProperties.dfy");
const output = join(
  root,
  "web/standalone/src/wasm/collab/generated/projection-kernel.js",
);
const declarations = output.replace(/\.js$/, ".d.ts");
const dafnyCwd = join(root, "web/standalone");
const dafny = process.env.DAFNY || "dafny";
const checkOnly = process.argv.includes("--check");

function runDafny(args) {
  try {
    return execFileSync(dafny, args, {
      // Dafny validates the emitted JavaScript by loading it. Resolve its
      // pinned bignumber.js runtime from the package that consumes the output.
      cwd: dafnyCwd,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    });
  } catch (error) {
    if (error.stdout) process.stdout.write(error.stdout);
    if (error.stderr) process.stderr.write(error.stderr);
    throw error;
  }
}

const version = runDafny(["--version"]).trim();
if (version !== REQUIRED_DAFNY) {
  throw new Error(
    `Dafny ${REQUIRED_DAFNY} is required; found ${version || "no version"}`,
  );
}

const sourceBytes = readFileSync(source);
const sourceSha256 = createHash("sha256").update(sourceBytes).digest("hex");
const temporary = mkdtempSync(join(tmpdir(), "pcbjam-dafny-"));

let generated;
try {
  const outputBase = join(temporary, "projection-kernel");
  const verification = runDafny([
    "build",
    "--target:js",
    "--enforce-determinism",
    `--output:${outputBase}`,
    source,
  ]);
  process.stdout.write(verification);
  generated = readFileSync(`${outputBase}.js`, "utf8");
} finally {
  rmSync(temporary, { recursive: true, force: true });
}

const commonJsImport = "const BigNumber = require('bignumber.js');";
if (!generated.includes(commonJsImport)) {
  throw new Error("Dafny JavaScript runtime import changed; review the adapter");
}

generated = generated.replace(
  commonJsImport,
  'import BigNumber from "bignumber.js";',
);

const banner = `// @generated by formal/yjs/generate-projection-kernel.mjs\n// Dafny: ${REQUIRED_DAFNY}\n// Source SHA-256: ${sourceSha256}\n// Do not edit this file; edit YjsProperties.dfy and regenerate.\n\n`;
const adapter =
  [
    "",
    "// This adapter is the only handwritten transformation around Dafny's output.",
    "// The decision itself executes ProjectionKernel.ExportAckDecision above.",
    "export function decideProjectionAck(",
    "  ownerMatches,",
    "  requestMatches,",
    "  dirty,",
    "  ok,",
    "  retryable,",
    ") {",
    "  const encoded = ProjectionKernel.__default.ExportAckDecision(",
    "    ownerMatches,",
    "    requestMatches,",
    "    dirty,",
    "    ok,",
    "    retryable,",
    "  );",
    "  const action = Number(encoded.toString());",
    "  if (!Number.isInteger(action) || action < 0 || action > 4) {",
    "    throw new Error(`verified projection kernel returned invalid action ${action}`);",
    "  }",
    "  return action;",
    "}",
    "",
    "// Hard non-item drift is never hot-applicable. Exact library drift may",
    "// cross the item bridge only when the runtime proved every changed",
    "// definition is carried by the submitted symbol-root wire.",
    "export function decideStructuralProjection(",
    "  hardMatches,",
    "  librariesMatch,",
    "  allLibraryChangesCovered,",
    ") {",
    "  const encoded = StructuralProjection.__default.ExportStructuralProjectionDecision(",
    "    hardMatches,",
    "    librariesMatch,",
    "    allLibraryChangesCovered,",
    "  );",
    "  const action = Number(encoded.toString());",
    "  if (action !== 1 && action !== 4) {",
    "    throw new Error(`verified structural projection kernel returned invalid action ${action}`);",
    "  }",
    "  return action;",
    "}",
    "",
    "// Native emissions are safe to publish normally only when no projection",
    "// ticket is awaiting acknowledgement. The decision is verified in Dafny.",
    "export function decideNativeEmission(projectionInFlight) {",
    "  const encoded = ProjectionKernel.__default.ExportNativeEmissionDecision(",
    "    projectionInFlight,",
    "  );",
    "  const action = Number(encoded.toString());",
    "  if (action !== 1 && action !== 4) {",
    "    throw new Error(`verified projection kernel returned invalid emission action ${action}`);",
    "  }",
    "  return action;",
    "}",
  ].join("\n") + "\n";

const expectedJavaScript = banner + generated + adapter;
const expectedDeclarations =
  [
    "// @generated by formal/yjs/generate-projection-kernel.mjs",
    "export type ProjectionAckAction = 0 | 1 | 2 | 3 | 4;",
    "export declare function decideProjectionAck(",
    "  ownerMatches: boolean,",
    "  requestMatches: boolean,",
    "  dirty: boolean,",
    "  ok: boolean,",
    "  retryable: boolean,",
    "): ProjectionAckAction;",
    "export type StructuralProjectionAction = 1 | 4;",
    "export declare function decideStructuralProjection(",
    "  hardMatches: boolean,",
    "  librariesMatch: boolean,",
    "  allLibraryChangesCovered: boolean,",
    "): StructuralProjectionAction;",
    "export type NativeEmissionAction = 1 | 4;",
    "export declare function decideNativeEmission(",
    "  projectionInFlight: boolean,",
    "): NativeEmissionAction;",
  ].join("\n") + "\n";

if (checkOnly) {
  const currentJavaScript = readFileSync(output, "utf8");
  const currentDeclarations = readFileSync(declarations, "utf8");
  if (
    currentJavaScript !== expectedJavaScript ||
    currentDeclarations !== expectedDeclarations
  ) {
    throw new Error("verified projection kernel is stale; regenerate it");
  }
  process.stdout.write("Verified projection kernel is current.\n");
} else {
  writeFileSync(output, expectedJavaScript);
  writeFileSync(declarations, expectedDeclarations);
  process.stdout.write(`Wrote ${output}\n`);
  process.stdout.write(`Wrote ${declarations}\n`);
}
